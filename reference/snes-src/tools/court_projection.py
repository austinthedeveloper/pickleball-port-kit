"""Single source of truth for the court's world-to-screen projection (ADR-011).

Both tools/art/prep_court_scene.py (which paints the court lines) and
tools/generate_assets.py (which emits assets/generated/court_projection.h for
the game) import this module, so art and rules cannot drift apart.

    s(y)     = 8.8 horizontal scale for world row y (clamped to 0..223)
    screen_x = 128 + round_half_up((world_x - 128) * s(y) / 256)
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ROWS = 224
SCALE_MIN = 192   # 0.75: PROJ-01 lower bound
SCALE_MAX = 281   # 1.10: PROJ-01 upper bound


def court_constants():
    text = (ROOT / "include" / "court.h").read_text(encoding="utf-8")
    result = {}
    for match in re.finditer(r"\b(COURT_[A-Z_]+)\s*=\s*(-?\d+)", text):
        result[match.group(1)] = int(match.group(2))
    return result


def scale_table(c=None):
    """s(y) for every screen row, linear between the sidelines."""
    c = c or court_constants()
    top, bottom = c["COURT_SIDELINE_TOP"], c["COURT_SIDELINE_BOTTOM"]
    s_top, s_bottom = c["COURT_PROJ_SCALE_TOP"], c["COURT_PROJ_SCALE_BOTTOM"]
    table = []
    for y in range(ROWS):
        num = (y - top) * (s_bottom - s_top)
        den = bottom - top
        # Round half up, consistent with the game's shift rounding.
        s = s_top + (2 * num + den) // (2 * den)
        table.append(max(SCALE_MIN, min(SCALE_MAX, s)))
    return table


def project_x(x, y, table):
    y = max(0, min(ROWS - 1, y))
    return 128 + (((x - 128) * table[y] + 128) >> 8)


def check(table, c=None):
    """PROJ-01..03; returns a list of failure messages."""
    c = c or court_constants()
    errors = []
    for y in range(1, ROWS):
        if table[y] < table[y - 1]:
            errors.append(f"PROJ-01: s(y) not monotonic at row {y}")
    if any(not SCALE_MIN <= s <= SCALE_MAX for s in table):
        errors.append("PROJ-01: s(y) outside [0.75, 1.10]")
    for y in range(ROWS):
        if project_x(c["COURT_NET_X"], y, table) != 128:
            errors.append(f"PROJ-02: net does not map to 128 on row {y}")
    for x in (c["COURT_BASELINE_LEFT"], c["COURT_BASELINE_RIGHT"]):
        for y in (c["COURT_SIDELINE_TOP"], c["COURT_SIDELINE_BOTTOM"]):
            sx = project_x(x, y, table)
            if not 8 <= sx <= 247:
                errors.append(f"PROJ-03: corner ({x},{y}) projects to {sx}")
    return errors


def header(table):
    values = [str(s - 256) for s in table]
    deltas = ",\n    ".join(", ".join(values[i:i + 16])
                              for i in range(0, len(values), 16))
    return (
        "/* Generated by tools/generate_assets.py from include/court.h; "
        "do not edit. */\n"
        "#ifndef COURT_PROJECTION_H\n#define COURT_PROJECTION_H\n\n"
        "/* s(y) - 256 per screen row (ADR-011). Storing the delta keeps\n"
        " * (x - 128) * delta inside 16 bits. */\n"
        f"#define COURT_PROJECTION_ROWS {ROWS}\n"
        "extern const signed char g_court_projection_delta"
        "[COURT_PROJECTION_ROWS];\n\n"
        "#ifdef COURT_PROJECTION_DEFINE\n"
        "const signed char g_court_projection_delta[COURT_PROJECTION_ROWS] = {\n"
        f"    {deltas}\n}};\n#endif\n\n#endif\n")
